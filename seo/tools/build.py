MAIN_RE = re.compile(r'<main id="main">.*?</main>', re.S)


def build_page(p):
    fp = os.path.join(ROOT, p['file'])
    if not os.path.exists(fp) and '--skip-missing' in sys.argv:
        return False
    src = open(fp, encoding='utf-8').read()
    m = MAIN_RE.search(src)
    if not m:
        sys.exit(f'No <main id="main"> in {p["file"]}')
    main_html = m.group(0)
    out = [head_html(p, main_html), '<body>', '    <a class="skip-link" href="#main">Skip to content</a>', '',
           nav_html(p.get('nav')), '', '    ' + main_html, '']
    out.append(breadcrumb_html(p['crumbs']) if p.get('crumbs') else '')
    out += [footer_html(), '</body>', '</html>', '']
    text = '\n'.join(out)
    text = re.sub(r'\n{3,}', '\n\n', text)
    if text != src:
        open(fp, 'w', encoding='utf-8').write(text)
        return True
    return False


def build_sitemap():
    urls = [p for p in PAGES if p.get('sitemap', True) and os.path.exists(os.path.join(ROOT, p['file']))]
    body = '\n'.join(f'  <url>\n    <loc>{SITE}{p["path"]}</loc>\n    <lastmod>{p["lastmod"]}</lastmod>\n  </url>' for p in urls)
    xml = f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{body}\n</urlset>\n'
    open(os.path.join(ROOT, 'sitemap.xml'), 'w').write(xml)
    return [f'{SITE}{p["path"]}' for p in urls]


