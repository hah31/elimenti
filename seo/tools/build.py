def service(path, name, description, area=None, service_type='Web design', offers=PRICE_FROM_4000, audience=None):
    node = {
        '@type': 'Service',
        '@id': f'{SITE}{path}#service',
        'name': name,
        'serviceType': service_type,
        'url': f'{SITE}{path}',
        'description': description,
        'provider': PROVIDER,
        'areaServed': area or AREA_SERVED,
    }
    if offers:
        node['offers'] = offers
    if audience:
        node['audience'] = {'@type': 'BusinessAudience', 'name': audience}
    return node


