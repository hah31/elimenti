def esc(s):
    return html.escape(s, quote=True)


def ld(obj):
    text = json.dumps(obj, indent=2, ensure_ascii=False).replace('</', '<\\/')
    return '    <script type="application/ld+json">\n' + '\n'.join('    ' + line for line in text.split('\n')) + '\n    </script>'


def faq_nodes(main_html, path):
    soup = BeautifulSoup(main_html, 'lxml')
    items = []
    for item in soup.select('.faq-item'):
        q = item.find(['h2', 'h3'])
        answer = ' '.join(p.get_text(' ', strip=True) for p in item.find_all('p'))
        if q and answer:
            items.append({'@type': 'Question', 'name': q.get_text(' ', strip=True),
                          'acceptedAnswer': {'@type': 'Answer', 'text': re.sub(r'\s+', ' ', answer)}})
    if not items:
        return []
    return [{'@type': 'FAQPage', '@id': f'{SITE}{path}#faq', 'mainEntity': items}]


def breadcrumb_ld(crumbs):
    trail = [('Home', '/')] + crumbs
    return {'@type': 'BreadcrumbList', 'itemListElement': [
        {'@type': 'ListItem', 'position': i + 1, 'name': n, 'item': f'{SITE}{p}'} for i, (n, p) in enumerate(trail)]}


def breadcrumb_html(crumbs):
    trail = [('Home', '/')] + crumbs
    lis = []
    for i, (n, p) in enumerate(trail):
        if i == len(trail) - 1:
            lis.append(f'            <li><span aria-current="page">{esc(n)}</span></li>')
        else:
            lis.append(f'            <li><a href="{p}">{esc(n)}</a></li>')
    return '    <nav class="breadcrumb" aria-label="Breadcrumb">\n        <ol>\n' + '\n'.join(lis) + '\n        </ol>\n    </nav>\n\n'


